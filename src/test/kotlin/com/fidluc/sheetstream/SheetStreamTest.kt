    @Test
    fun testCustomStylesAndFreezePanes() {
        val bos = ByteArrayOutputStream()

        bos.sheetStream {
            val customBrand = customStyle {
                backgroundColor = "#0D47A1"
                textColor = "#FFFFFF"
                bold = true
                numberFormat = "[$$-409]#,##0.00"
                centered = true
            }

            sheet("StyledSheet") {
                freezeHeaderRow()
                row {
                    cell("Corporate Header", customBrand)
                    cell(1250.75, customBrand)
                }
            }
        }

        val bytes = bos.toByteArray()
        var sheetXml = ""
        var stylesXml = ""
        ZipInputStream(bytes.inputStream()).use { zis ->
            var entry = zis.nextEntry
            while (entry != null) {
                if (entry.name == "xl/worksheets/sheet1.xml") {
                    sheetXml = zis.bufferedReader(Charsets.UTF_8).readText()
                } else if (entry.name == "xl/styles.xml") {
                    stylesXml = zis.bufferedReader(Charsets.UTF_8).readText()
                }
                entry = zis.nextEntry
            }
        }

        // Verify Freeze Panes
        assertTrue(sheetXml.contains("""<pane ySplit="1""""), "Must contain ySplit=1 for frozen header")
        assertTrue(sheetXml.contains("""state="frozen""""), "Pane state must be frozen")
        val panePos = sheetXml.indexOf("<pane")
        val sheetDataPos = sheetXml.indexOf("<sheetData>")
        assertTrue(panePos < sheetDataPos, "<pane> must precede <sheetData> per OOXML spec")

        // Verify Custom Styles in styles.xml
        assertTrue(stylesXml.contains("FF0D47A1"), "styles.xml must contain custom background hex FF0D47A1")
        assertTrue(stylesXml.contains("FFFFFFFF"), "styles.xml must contain custom text color hex FFFFFFFF")
        assertTrue(stylesXml.contains("[$$-409]#,##0.00"), "styles.xml must contain custom number format code")
        assertTrue(stylesXml.contains("""applyAlignment="1""""), "styles.xml must apply alignment")
    }

    @Test
    fun testReaderRoundTrip() {
        val tempFile = File.createTempFile("sheetstream_roundtrip_", ".xlsx")
        try {
            // 1. Write workbook with SheetStream
            tempFile.sheetStream {
                sheet("Ledger") {
                    headerRow("Date", "Category", "Amount", "IsVerified")
                    row("2026-10-01", "Hardware", 850.50, true)
                    row("2026-10-02", "Office Supplies", 42.00, false)
                    row("2026-10-03", "Cloud Hosting", 120.00, true)
                }
                sheet("Summary") {
                    headerRow("Metric", "Value")
                    row {
                        cell("Total Hardware")
                        formula("SUM('Ledger'!C2:C4)", CellStyle.CURRENCY)
                    }
                }
            }

            // 2. Read workbook back with SheetStream Reader
            var verifiedSheetsCount = 0
            var ledgerRowsCount = 0

            tempFile.readSpreadsheet {
                assertEquals(listOf("Ledger", "Summary"), sheetNames, "Must discover both sheet names")

                sheet("Ledger") {
                    forEachRow { row ->
                        ledgerRowsCount++
                        if (row.rowNum == 1) {
                            assertEquals("Date", row.getString("A"))
                            assertEquals("Category", row.getString("B"))
                            assertEquals("Amount", row.getString("C"))
                            assertEquals("IsVerified", row.getString("D"))
                        } else if (row.rowNum == 2) {
                            assertEquals("2026-10-01", row.getString(1))
                            assertEquals("Hardware", row.getString("B"))
                            assertEquals(850.50, row.getDouble(3))
                            assertEquals(850, row.getInt(3))
                            assertEquals(true, row.getBoolean(4))
                        } else if (row.rowNum == 3) {
                            assertEquals("Office Supplies", row.getString(2))
                            assertEquals(42.00, row.getDouble(3))
                            assertEquals(false, row.getBoolean(4))
                        }
                    }
                }

                sheet("Summary") {
                    verifiedSheetsCount++
                    val rows = toRowList()
                    assertEquals(2, rows.size, "Summary should have 2 rows")
                    assertEquals("Metric", rows[0].getString("A"))
                    assertEquals("Total Hardware", rows[1].getString(1))
                    assertEquals("SUM('Ledger'!C2:C4)", rows[1].getFormula(2))
                }
            }

            assertEquals(4, ledgerRowsCount, "Must have read 4 rows in Ledger")
            assertEquals(1, verifiedSheetsCount, "Must have read Summary sheet")
        } finally {
            tempFile.delete()
        }
    }

    @Test
    fun testStandardOoxmlStructureValidation() {
        val tempFile = File.createTempFile("sheetstream_ooxml_val_", ".xlsx")
        try {
            // 1. Write workbook with SheetStream
            tempFile.sheetStream {
                sheet("OoxmlValidationSheet") {
                    headerRow("ID", "Customer", "Balance")
                    row(101, "Acme Corp", 1540.25)
                    row(102, "Globex Inc", 980.50)
                }
            }

            // 2. Validate ZIP and OOXML structure using standard Java runtime only
            java.util.zip.ZipFile(tempFile).use { zip ->
                assertNotNull(zip.getEntry("[Content_Types].xml"), "Must contain [Content_Types].xml")
                assertNotNull(zip.getEntry("_rels/.rels"), "Must contain _rels/.rels")
                assertNotNull(zip.getEntry("xl/workbook.xml"), "Must contain xl/workbook.xml")
                assertNotNull(zip.getEntry("xl/_rels/workbook.xml.rels"), "Must contain workbook rels")
                assertNotNull(zip.getEntry("xl/styles.xml"), "Must contain styles.xml")
                assertNotNull(zip.getEntry("xl/worksheets/sheet1.xml"), "Must contain sheet1.xml")

                // Parse sheet1.xml using standard DOM parser to verify strict XML compliance
                val sheetEntry = zip.getEntry("xl/worksheets/sheet1.xml")!!
                val doc = javax.xml.parsers.DocumentBuilderFactory.newInstance().newDocumentBuilder()
                    .parse(zip.getInputStream(sheetEntry))
                val rows = doc.getElementsByTagName("row")
                assertEquals(3, rows.length, "Must have exactly 3 row elements")
            }
        } finally {
            tempFile.delete()
        }
    }

    @Test
    fun testSafetyLimitsEnforcement() {
        val tempFile = File.createTempFile("sheetstream_limits_", ".xlsx")
        try {
            tempFile.sheetStream {
                sheet("LimitsTest") {
                    headerRow("Col1", "Col2")
                    row("Val1", "Val2")
                }
            }

            // 1. Verify File Size Limit Throws
            var caughtSizeLimit = false
            try {
                tempFile.readSpreadsheet(config = ReaderConfig(maxFileSizeBytes = 10)) {
                    sheet("LimitsTest") {
                        forEachRow { /* no-op */ }
                    }
                }
            } catch (e: SheetStreamLimitExceededException) {
                if (e.limitType == LimitType.FILE_SIZE) {
                    caughtSizeLimit = true
                }
            }
            assertTrue(caughtSizeLimit, "Must throw SheetStreamLimitExceededException for FILE_SIZE")

            // 2. Verify Writer Column Limit Throws when exceeding 16,384 columns
            var caughtColumnLimit = false
            try {
                val bos = ByteArrayOutputStream()
                bos.sheetStream {
                    sheet("WideSheet") {
                        row {
                            skip(16_385)
                        }
                    }
                }
            } catch (e: SheetStreamLimitExceededException) {
                if (e.limitType == LimitType.COLUMN_COUNT) {
                    caughtColumnLimit = true
                }
            }
            assertTrue(caughtColumnLimit, "Must throw SheetStreamLimitExceededException for COLUMN_COUNT")
        } finally {
            tempFile.delete()
        }
    }
