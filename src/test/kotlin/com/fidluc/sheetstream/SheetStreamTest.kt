    @Test
    fun testGeneratedZipContainsAllRequiredOoxmlEntries() {
        val bos = ByteArrayOutputStream()

        SheetStream.build(bos) {
            sheet("Tab1") {
                row {
                    cell("Header 1", CellStyle.HEADER)
                    cell("Header 2", CellStyle.HEADER)
                }
                row {
                    cell("Value A")
                    cell(100.50, CellStyle.CURRENCY)
                }
            }
            sheet("Tab2") {
                row {
                    cell("Cross Ref", CellStyle.BOLD)
                    formula("'Tab1'!B2", CellStyle.CURRENCY)
                }
            }
        }

        val bytes = bos.toByteArray()
        assertTrue(bytes.isNotEmpty(), "Generated bytes must not be empty")

        // Inspect ZIP entries
        val entryNames = mutableSetOf<String>()
        ZipInputStream(bytes.inputStream()).use { zis ->
            var entry = zis.nextEntry
            while (entry != null) {
                entryNames.add(entry.name)
                entry = zis.nextEntry
            }
        }

        assertTrue(entryNames.contains("[Content_Types].xml"), "Must contain [Content_Types].xml")
        assertTrue(entryNames.contains("_rels/.rels"), "Must contain _rels/.rels")
        assertTrue(entryNames.contains("xl/workbook.xml"), "Must contain xl/workbook.xml")
        assertTrue(entryNames.contains("xl/_rels/workbook.xml.rels"), "Must contain xl/_rels/workbook.xml.rels")
        assertTrue(entryNames.contains("xl/styles.xml"), "Must contain xl/styles.xml")
        assertTrue(entryNames.contains("xl/worksheets/sheet1.xml"), "Must contain sheet1.xml")
        assertTrue(entryNames.contains("xl/worksheets/sheet2.xml"), "Must contain sheet2.xml")
    }

    @Test
    fun testConvenienceRowBuildersAndStyles() {
        val bos = ByteArrayOutputStream()

        bos.sheetStream {
            sheet("Data") {
                setColumnWidths(15.0, 25.0, 15.0)

                headerRow("Col 1", "Col 2", "Col 3")
                subheaderRow("Section A", "Sub 2", "Sub 3")

                row("Simple Text", 42, true)

                row {
                    emptyCell(CellStyle.SUBHEADER)
                    cellAny("Universal Cell", CellStyle.BOLD)
                    cells(100.5, "Bulk Item", false)
                }
            }
        }

        val bytes = bos.toByteArray()
        assertTrue(bytes.isNotEmpty())

        var sheet1Xml = ""
        ZipInputStream(bytes.inputStream()).use { zis ->
            var entry = zis.nextEntry
            while (entry != null) {
                if (entry.name == "xl/worksheets/sheet1.xml") {
                    sheet1Xml = zis.bufferedReader(Charsets.UTF_8).readText()
                    break
                }
                entry = zis.nextEntry
            }
        }

        assertTrue(sheet1Xml.contains("<cols>"), "Must define column widths")
        assertTrue(sheet1Xml.contains("""width="15.0""""), "Must contain custom width")
        assertTrue(sheet1Xml.contains("Col 1"), "Must contain header cell content")
        assertTrue(sheet1Xml.contains("""s="1""""), "Header must use style index 1")
        assertTrue(sheet1Xml.contains("""s="2""""), "Subheader must use style index 2")
        assertTrue(sheet1Xml.contains("<v>42</v>"), "Must contain integer number value")
        assertTrue(sheet1Xml.contains("""t="b"><v>1</v>"""), "Must contain boolean true value")
    }

    @Test
    fun testStreamPagedSimulatingRoomDb() {
        val bos = ByteArrayOutputStream()

        data class MockRecord(val id: Int, val title: String, val amount: Double)

        // Mock database with 125 records
        val allDbRecords = (1..125).map { MockRecord(it, "Item #$it", it * 10.5) }

        bos.sheetStream {
            sheet("PagedExport") {
                headerRow("ID", "Title", "Amount")

                // Page in chunks of 50
                streamPaged(
                    chunkSize = 50,
                    fetchChunk = { offset, limit ->
                        allDbRecords.drop(offset).take(limit)
                    }
                ) { record ->
                    cell(record.id)
                    cell(record.title)
                    cell(record.amount, CellStyle.CURRENCY)
                }
            }
        }

        val bytes = bos.toByteArray()
        var sheet1Xml = ""
        ZipInputStream(bytes.inputStream()).use { zis ->
            var entry = zis.nextEntry
            while (entry != null) {
                if (entry.name == "xl/worksheets/sheet1.xml") {
                    sheet1Xml = zis.bufferedReader(Charsets.UTF_8).readText()
                    break
                }
                entry = zis.nextEntry
            }
        }

        // Header is row 1, 125 records follow => last row is row 126
        assertTrue(sheet1Xml.contains("""<row r="1">"""), "Must have row 1")
        assertTrue(sheet1Xml.contains("""<row r="126">"""), "Must have row 126 for the last record")
        assertTrue(sheet1Xml.contains("Item #125"), "Must have last item")
    }

